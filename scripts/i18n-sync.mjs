import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const manifest = JSON.parse(readFileSync(path.join(root, "public/locales/manifest.json"), "utf8"));
const locales = Object.entries(manifest.locales).filter(([, value]) => value.enabled).map(([code]) => code);
if (!locales.includes(manifest.defaultLocale)) throw new Error("The default locale must be enabled");
for (const [code, definition] of Object.entries(manifest.locales)) {
  if (!/^[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*$/.test(code) || Intl.getCanonicalLocales(code)[0] !== code) throw new Error(`Invalid locale: ${code}`);
  if (!["ltr", "rtl"].includes(definition.direction) || !definition.label?.trim() || !definition.languageName?.trim()) throw new Error(`Incomplete locale metadata: ${code}`);
  if (!manifest.locales[definition.fallback]?.enabled) throw new Error(`Fallback must be an enabled locale: ${code}`);
  if (Intl.getCanonicalLocales(definition.intl).length !== 1) throw new Error(`Invalid Intl locale: ${code}`);
  if (definition.enabled && !existsSync(path.join(root, `public/locales/${code}/common.json`))) throw new Error(`Missing dictionary: ${code}`);
}
const output = `// Generated by npm run i18n:sync. Edit public/locales/manifest.json and the dictionaries.\n`
  + locales.map((code, index) => `import dictionary${index} from "../../public/locales/${code}/common.json" with { type: "json" };`).join("\n")
  + `\nexport const localeResources: Record<string, { common: Record<string, unknown> }> = {\n`
  + locales.map((code, index) => `  ${JSON.stringify(code)}: { common: dictionary${index} },`).join("\n") + "\n};\n";
const target = path.join(root, "src/lib/localeResources.generated.ts");
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== output) throw new Error("Language resources are out of date. Run npm run i18n:sync");
} else if (!existsSync(target) || readFileSync(target, "utf8") !== output) writeFileSync(target, output);
console.log(`Language resources: ${locales.join(", ")}`);
const errorMessages = Object.fromEntries(locales.map(code => {
  const dictionary = JSON.parse(readFileSync(path.join(root, `public/locales/${code}/common.json`), "utf8"));
  const fallback = JSON.parse(readFileSync(path.join(root, `public/locales/${manifest.locales[code].fallback}/common.json`), "utf8"));
  return [code, { ...fallback.globalError, ...dictionary.globalError }];
}));
const errorsOutput = "// Generated by npm run i18n:sync. Small standalone root error boundary copy.\nexport const localeErrorMessages = " + JSON.stringify(errorMessages, null, 2) + ";\n";
const errorsPath = path.join(root, "src/lib/localeErrors.generated.ts");
if (process.argv.includes("--check")) {
  if (!existsSync(errorsPath) || readFileSync(errorsPath, "utf8") !== errorsOutput) throw new Error("Error translations are out of date. Run npm run i18n:sync");
} else if (!existsSync(errorsPath) || readFileSync(errorsPath, "utf8") !== errorsOutput) writeFileSync(errorsPath, errorsOutput);
